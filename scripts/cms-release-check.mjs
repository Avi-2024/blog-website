const failures=[];
const required=['DATABASE_URL','CMS_ADMIN_ORIGIN','NEXT_PUBLIC_SITE_URL','CRON_SECRET'];
for(const k of required)if(!process.env[k])failures.push(k+' missing');
if((process.env.CRON_SECRET||'').length<32)failures.push('CRON_SECRET must be 32+ characters');
for(const k of ['CMS_ADMIN_ORIGIN','NEXT_PUBLIC_SITE_URL'])if(process.env[k]&&!process.env[k].startsWith('https://'))failures.push(k+' must use HTTPS');
const cloud=['CLOUDINARY_CLOUD_NAME','CLOUDINARY_API_KEY','CLOUDINARY_API_SECRET'];
const cloudSelected=cloud.some(k=>Boolean(process.env[k]));
const cloudReady=cloud.every(k=>Boolean(process.env[k]));
const s3Selected=Boolean(process.env.S3_BUCKET||process.env.MEDIA_PUBLIC_URL);
const s3Ready=Boolean(process.env.S3_BUCKET&&process.env.MEDIA_PUBLIC_URL&&process.env.AWS_ACCESS_KEY_ID&&process.env.AWS_SECRET_ACCESS_KEY);
if(cloudSelected&&!cloudReady)failures.push('Cloudinary configuration incomplete: set CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY and CLOUDINARY_API_SECRET');
if(cloudReady&&!/^[a-zA-Z0-9_-]+$/.test(process.env.CLOUDINARY_CLOUD_NAME||''))failures.push('Invalid Cloudinary cloud name');
if(!cloudReady&&!s3Ready)failures.push('Configure complete Cloudinary credentials or S3-compatible media storage');
if(!cloudSelected&&s3Selected&&!s3Ready)failures.push('S3 credentials, bucket or media URL missing');
if(s3Ready&&!process.env.MEDIA_PUBLIC_URL.startsWith('https://'))failures.push('MEDIA_PUBLIC_URL must use HTTPS');
if(process.env.CMS_LOCAL_MODE==='true')failures.push('Disable CMS_LOCAL_MODE');
if(process.env.STAGING_NOINDEX!=='false')failures.push('Production indexing disabled');
if(process.env.CMS_ADMIN_ORIGIN!==process.env.NEXT_PUBLIC_SITE_URL?.replace(/\/$/,''))failures.push('Admin/public origins differ');
console.log(failures.length?failures.map(x=>'BLOCKED: '+x).join('\n'):'Environment checks passed; still run hosted acceptance and backup restoration.');
process.exitCode=failures.length?1:0;
